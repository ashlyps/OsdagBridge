"""Data-driven report plots; missing engineering values are never invented."""
import os
import re
import math
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from .styles import CHART_STYLE


def _number(value):
    if value is None or isinstance(value, bool):
        return None
    try:
        value = float(str(value).replace(',', '').strip())
        return value if math.isfinite(value) and value >= 0 else None
    except (ValueError, TypeError):
        return None


def _save_bar(labels, values, path, title, ylabel, threshold=False):
    if not values:
        return False
    fig, ax = plt.subplots(figsize=(9, max(3.5, 0.45 * len(labels) + 1.5)))
    y = list(range(len(labels)))
    colors = [(CHART_STYLE['fail_color'] if threshold and v > CHART_STYLE['ur_threshold'] else CHART_STYLE['pass_color']) for v in values]
    ax.barh(y, values, color=colors)
    ax.set_yticks(y, labels)
    ax.invert_yaxis()
    ax.set_xlabel(ylabel)
    ax.set_title(title)
    ax.grid(axis='x', alpha=0.2)
    ax.set_axisbelow(True)
    if threshold:
        ax.axvline(CHART_STYLE['ur_threshold'], color='red', linestyle='--', label='UR = 1.0')
        ax.legend(loc='lower right')
    for i, value in enumerate(values):
        ax.text(value, i, f' {value:.2f}', va='center', fontsize=8)
    fig.tight_layout()
    fig.savefig(path, dpi=CHART_STYLE['dpi'], bbox_inches='tight')
    plt.close(fig)
    return True


def design_ur_chart(chapter_tex, folder):
    """Read actual UR cells from the Chapter 5 summary table."""
    match = re.search(r'\\caption\{\\textbf\{Overall Design Check Summary --- All Members\}\}(.*?)\\end\{longtable\}', chapter_tex, re.S)
    if not match:
        return None
    rows = []
    for line in match.group(1).splitlines():
        if ' & ' not in line or 'textbf' in line or 'multicolumn' in line:
            continue
        cells = line.split(' & ')
        if len(cells) != 5:
            continue
        name = re.sub(r'\\[a-zA-Z]+', '', cells[0]).replace('---', '-').strip()
        ur = cells[-1].split(r'\\')[0]
        ur = re.sub(r'\\textcolor\{[^}]*\}\{([^}]*)\}', r'\1', ur).strip()
        value = _number(ur)
        if value is not None and name:
            rows.append((name, value))
    if not rows:
        return None
    path = os.path.join(folder, 'utilization_summary.png')
    _save_bar([a for a,b in rows], [b for a,b in rows], path, 'Overall design utilization ratios', 'Demand / Capacity', True)
    return path


def quantity_charts(data, folder):
    groups = [
        ('Structural steel quantities', 'Weight (MT)', 'steel_quantities.png', [
            ('Girders', ['steel_girders_wt_total']),
            ('Cross bracing', ['bracing_top_wt_total', 'bracing_bot_wt_total', 'bracing_diag_wt_total']),
            ('End diaphragms', ['end_diaphragm_wt_total', 'end_diaphragms_wt_total'])]),
        ('Concrete deck quantity', 'Volume (m3)', 'concrete_quantity.png', [
            ('Concrete deck', ['concrete_deck_vol_total'])]),
        ('Reinforcement quantity', 'Weight (MT)', 'reinforcement_quantity.png', [
            ('Reinforcement steel', ['rebar_deck_wt_total'])]),
    ]
    results = []
    for title, unit, filename, entries in groups:
        labels, values = [], []
        for label, keys in entries:
            numbers = [_number(data.get(key)) for key in keys]
            valid = [x for x in numbers if x is not None]
            if valid:
                labels.append(label)
                values.append(sum(valid))
        if values:
            path = os.path.join(folder, filename)
            _save_bar(labels, values, path, title, unit)
            results.append((path, title))
    return results


def latex_figure(path, caption):
    # Only paths generated by this module are accepted here.
    path = path.replace('\\', '/')
    return (r'\begin{figure}[htbp]' + '\n' + r'\centering' + '\n'
            + r'\includegraphics[width=0.88\textwidth,height=0.72\textheight,keepaspectratio]{'
            + path + '}\n' + r'\caption{' + caption + '}\n' + r'\end{figure}' + '\n')
